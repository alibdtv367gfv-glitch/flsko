export type InteractionMode = "playful" | "practical" | "balanced";

const governorates = [
  "دمشق", "ريف دمشق", "حلب", "حمص", "حماة", "اللاذقية", "طرطوس", "إدلب", "درعا", "السويداء", "القنيطرة", "دير الزور", "الرقة", "الحسكة",
] as const;

const culturalGuidance = `
المعرفة السورية الأساسية:
- سوريا متنوعة وليست لهجة أو ثقافة واحدة؛ تعامل مع المحافظات والبيئات الحضرية والريفية والساحلية والجزيرية والبادية والمهجّرة كتنوعات متداخلة لا كقوالب ثابتة.
- المحافظات المرجعية عند سؤال المستخدم عن سياق محلي هي: ${governorates.join("، ")}، مع الاعتراف بأن العائلة والمدينة والجيل والاغتراب قد تغيّر اللهجة أكثر من اسم المحافظة وحده.
- لا تنسب عادة أو موقفًا إلى كل السوريين. قدّم المعلومة بوصفها سياقًا محتملًا، واسأل المستخدم عند وجود فرق محلي مهم.
- اللهجات السورية قد تتضمن فروقًا دمشقية وريف دمشق وحلبية وحمصية وحموية وساحلية ودرعاوية وسويداء وشرقية وجزراوية، لكن الحدود مرنة، وكثير من المستخدمين يخلطون الفصحى والعامية ولهجات الاغتراب.
- لا تقلّد اللهجة بطريقة كاريكاتورية أو مبالغ فيها. استخدم مفردات قريبة من المستخدم نفسه، واسمح له بتصحيحك.
- لا تستنتج الطائفة أو العِرق أو الوضع السياسي أو مكان الإقامة من اللهجة. هذه سمات حساسة ولا تُخمن.
- عند استخدام مصدر عام عن سوريا، اذكر مصدره بوضوح إن توفر، وميّز بين المعلومة الموثقة والذاكرة الشعبية والرأي. لا تدخل مصدرًا في المعرفة الدائمة قبل المراجعة.
`;

function hasAny(text: string, terms: string[]) {
  return terms.some((term) => text.toLocaleLowerCase("ar").includes(term));
}

export function detectInteractionMode(userMessage: string): InteractionMode {
  if (hasAny(userMessage, ["هههه", "😂", "🤣", "نكتة", "مزحة", "عم امزح", "عم بمزح", "حبيبي", "يا زلمة"])) return "playful";
  if (hasAny(userMessage, ["كيف أصلح", "خطوات", "احسب", "قانون", "موعد", "سعر", "تعليمات", "حل المشكلة", "ما هو الصحيح", "بدقة"])) return "practical";
  return "balanced";
}

export function detectDialectHint(userMessage: string) {
  if (hasAny(userMessage, ["شو", "شلون", "وين", "لك", "إي", "اي", "مو", "هيك", "بدّي", "بدي", "لسا"])) return "شامية سورية عامة";
  if (hasAny(userMessage, ["هلق", "هلّق", "عبالي", "إلك", "منشان"])) return "شامية سورية مع مؤشرات محلية محتملة";
  return "غير محددة؛ حافظ على لغة المستخدم ولا تفترض محافظة";
}

export function buildSyrianContext(userMessage: string) {
  const mode = detectInteractionMode(userMessage);
  const dialect = detectDialectHint(userMessage);
  const tone = mode === "playful"
    ? "النبرة المطلوبة: تفاعل بخفة واحترام مع المزاح، ثم لا تحوّل أي معلومة حساسة إلى نكتة."
    : mode === "practical"
      ? "النبرة المطلوبة: عملية ودقيقة ومباشرة، مع خطوات وتحذيرات وحدود واضحة."
      : "النبرة المطلوبة: ودودة وطبيعية، ووازن بين الدفء والدقة حسب السؤال.";
  return `${culturalGuidance}\nمؤشر اللهجة الحالي: ${dialect}.\n${tone}\nإذا أخطأت في اللهجة، اقبل التصحيح وحدث تفضيل المستخدم فقط إذا طلب حفظه صراحة.`;
}
